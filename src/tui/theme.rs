static THEME: AtomicUsize = AtomicUsize::new(0);

pub(super) fn pal() -> &'static Pal {
    &THEMES[THEME.load(Ordering::Relaxed)]
}

pub(super) fn theme_index(name: &str) -> usize {
    THEMES
        .iter()
        .position(|t| t.name == name.trim())
        .unwrap_or(0)
}

/// $BRIGD_THEME, else ~/.brigd/theme, else catppuccin-mocha.
pub(super) fn init_theme() {
    let name = env::var("BRIGD_THEME")
        .or_else(|_| fs::read_to_string(crate::store::root().join("theme")))
        .unwrap_or_default();
    THEME.store(theme_index(&name), Ordering::Relaxed);
}

pub(super) fn next_theme() -> &'static str {
    let i = (THEME.load(Ordering::Relaxed) + 1) % THEMES.len();
    THEME.store(i, Ordering::Relaxed);
    let _ = fs::write(
        crate::store::root().join("theme"),
        format!("{}\n", THEMES[i].name),
    ); // ponytail: best effort, lost write just means no persistence
    THEMES[i].name
}

/// Agent rows/tabs are tinted by stage; avoids the status-glyph and selection colors.
pub(super) fn stage_color(stage: Option<usize>) -> Color {
    let p = pal();
    let c = [p.mauve, p.yellow, p.blue, p.peach, p.pink, p.teal];
    stage.map_or(Color::Reset, |s| c[s % c.len()])
}
